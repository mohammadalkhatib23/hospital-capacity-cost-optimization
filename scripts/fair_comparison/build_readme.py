def ORDINAL_N(k):
    return f"{k}{'th' if 10 <= k % 100 <= 20 else {1: 'st', 2: 'nd', 3: 'rd'}.get(k % 10, 'th')}"


def build():
    return checkpoint.build() + "\n" + section()


def main():
    text, path = build(), REPO / "README.md"
    if "--check" in sys.argv[1:]:
        same = path.read_bytes() == text.encode("utf-8")
        print(f"README.md {'matches' if same else 'DOES NOT match'} the clean-checkpoint text plus the generated fair-comparison section ({len(text.splitlines())} lines)")
        sys.exit(0 if same else 1)
    path.write_bytes(text.encode("utf-8"))
    print(f"wrote README.md ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
