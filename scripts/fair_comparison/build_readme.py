def read(path):
    cols = pd.read_csv(path, nrows=0).columns
    return pd.read_csv(path, parse_dates=["month"] if "month" in cols else None, float_precision="round_trip")


def load():
    d = dict(decision=json.loads((DATA / "decision.json").read_text(encoding="utf-8")), log=json.loads((DATA / "fit_log.json").read_text(encoding="utf-8")),
             combined=read(DATA / "combined.csv").set_index("method"), imp=read(DATA / "improvements.csv").set_index(["scope", "method"]),
             sweep=read(DATA / "penalty_sweep.csv"), service=read(DATA / "service_level.csv"), origins={})
    d["config_sha"] = (DATA / "config.sha256").read_text(encoding="utf-8").split()[0]
    d["plans_sha"] = (DATA / "plans.sha256").read_text(encoding="utf-8").split()[0]
    assert d["decision"]["hashes"] == dict(config=d["config_sha"], plans_frozen=d["plans_sha"])
    for key in ORIGINS:
        d["origins"][key] = {n: read(DATA / key / f"{n}.csv") for n in ("accuracy", "forecasts", "actuals", "service_levels", "bank_summary")}
        d["origins"][key]["accuracy"] = d["origins"][key]["accuracy"].set_index("method")
    return d


def listing(names):
    names = list(names)
    return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]


def origin_section(d, key):
    stem, name, month = ORIGINS[key]
    acc, dec, c = d["origins"][key]["accuracy"], d["decision"]["per_origin"][key], d["combined"]
    lines = [f"#### {name}: {month}", "",
             "| Forecast | Gap MAE (beds) | Pinball loss at 0.9 (beds) | Coverage at 0.9 | Point LP cost | Protected (SAA) cost | Excess over hindsight (Protected) | Effect of protection |",
             "| --- | ---: | ---: | --- | ---: | ---: | ---: | --- |"]
    for m in METHODS:
        lines.append(f"| {m} | {beds(acc.loc[m, 'gap_mae'])} | {beds(acc.loc[m, 'pinball_090'])} | {dec['coverage_090'][m]} months | {money(c.loc[m, key + '_point'])} | "
                     f"{money(c.loc[m, key + '_protected'])} | {money(c.loc[m, key + '_protected_excess'])} | {dec['protection'][m]['effect']} |")
    prev, best = dec["previous_winner"], dec["joint_best_protected"]
    helped = [m for m in METHODS if dec["protection"][m]["effect"] == "helped"]
    hurt = [m for m in METHODS if dec["protection"][m]["effect"] == "hurt"]
    assert len(best) == 1 and best[0] == dec["cheapest_protected"] and not prev["still_wins"] and len(helped) + len(hurt) == len(METHODS)
    # protection helped exactly the methods whose point forecast was too low on average, and hurt those that were too high
    assert all((acc.loc[m, "gap_mean_signed_error"] > 0) == (m in helped) for m in METHODS)
    cheapest_point = c[key + "_point"].min()
    compare = ("cheaper than" if c.loc[best[0], key + "_protected"] < cheapest_point else "dearer than")
    lines += ["",
              f"Costs in millions of model units; hindsight cost {money(dec['hindsight_cost'])}m. Coverage: months in which the actual gap was at or below the "
              "method's 0.9 quantile forecast.", "",
              f"![Point plan vs Protected plan, {name}]({FIG}/{stem}_point_vs_protected.png)", "",
              f"**Result.** {best[0]} had the cheapest Protected plan ({money(c.loc[best[0], key + '_protected'])}m) and no other method was within the tie band. "
              f"{prev['method']}, which had the cheapest Point plan ({money(cheapest_point)}m), ranks {ORDINAL[prev['protected_rank']]} of 5 when protected "
              f"({money(c.loc[prev['method'], key + '_protected'])}m). Protection helped {listing(helped)}, whose forecasts had been too low on average, and hurt "
              f"{listing(hurt)}, whose forecasts had been too high. The cheapest Protected plan was {compare} the cheapest Point plan.", ""]
    return lines


def change_table(d):
    imp, c = d["imp"], d["combined"]
    scopes = list(ORIGINS) + ["combined"]
    triple = lambda m, col: " / ".join(money(imp.loc[(s, m), col]) for s in scopes)
    lines = ["| Forecast | Value of protection | Part from removing bias | Part from the margin | Protected excess over hindsight, both origins | Overall rank |",
             "| --- | ---: | ---: | ---: | ---: | --- |"]
    for m in d["decision"]["overall"]["ranking"]:
        lines.append(f"| {m} | {triple(m, 'value_of_protection')} | {triple(m, 'value_of_bias_correction')} | {triple(m, 'value_of_margin')} | "
                     f"{money(c.loc[m, 'combined_protected_excess'])} | {int(c.loc[m, 'overall_rank'])} |")
    assert c.overall_rank.is_unique
    return "\n".join(lines)


def robustness_table(d):
    sweep, service, dec = d["sweep"], d["service"], d["decision"]
    s = sweep[(sweep.scope == "combined") & (sweep.kind == "protected")]
    sl = service.groupby(["method", "alpha"]).total.sum().unstack()
    assert service.shortfall_bed_months.sum() == 0 and service.short_months.sum() == 0
    sl_rank = sl.rank(method="min").astype(int)
    lines = ["| Forecast | p = 1,000 (q* = 0.5) | p = 2,500 (q* = 0.8) | p = 5,000 (q* = 0.9, base) | p = 10,000 (q* = 0.95, indicative) | Service level, alpha = 0.10 | "
             "Service level, alpha = 0.05 (indicative) |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for m in METHODS:
        cells = []
        for p in (1000.0, 2500.0, 5000.0, 10000.0):
            r = s[np.isclose(s.penalty, p) & (s.method == m)].iloc[0]
            cells.append(f"{int(r['rank'])} ({money(r.excess)})")
        cells += [f"{sl_rank.loc[m, a]} ({money(sl.loc[m, a])})" for a in (0.10, 0.05)]
        lines.append(f"| {m} | " + " | ".join(cells) + " |")
    outcome = lambda p: dec["penalty_sweep"][f"{p:g}"]["outcome"]
    lines.append("| **Clear winner** | " + " | ".join(outcome(p) for p in (1000.0, 2500.0, 5000.0, 10000.0)) + " | not declared | not declared |")
    return "\n".join(lines), {a: sl[a].idxmin() for a in (0.10, 0.05)}


def answer(d):
    dec, c, imp = d["decision"], d["combined"], d["imp"]
    o1, o2 = (dec["per_origin"][k] for k in ORIGINS)
    cal, sweep = dec["best_calibrated"], dec["penalty_sweep"]
    covered = sum(int(d["origins"][k]["accuracy"].covered_090.sum()) for k in ORIGINS)
    months = sum(int(d["origins"][k]["accuracy"].months.sum()) for k in ORIGINS)
    order = dec["overall"]["ranking"]
    assert dec["overall"]["outcome"] == "no clear winner" and o1["joint_best_protected"] == ["ExtraTrees-24"] and o2["joint_best_protected"] == ["Seasonal naive"]
    assert o1["previous_winner"] == dict(method="SARIMA-24", still_wins=False, protected_rank=5, protected_joint_best=["ExtraTrees-24"])
    assert o2["previous_winner"] == dict(method="Persistence", still_wins=False, protected_rank=5, protected_joint_best=["Seasonal naive"])
    assert order[0] == "Seasonal naive" and order[1] == "ExtraTrees-24"
    assert cal["method"] == "ExtraTrees-24" and not cal["clear"] and cal["lowest_per_origin"] == {"O1_sep2025": "ExtraTrees-24", "O2_mar2026": "SARIMA-24"}
    assert [sweep[k]["outcome"] for k in ("1000", "2500", "5000", "10000")] == ["Mean-24", "no clear winner", "no clear winner", "Seasonal naive"]
    assert not dec["robust_to_penalty"]
    for k in ORIGINS:  # protection helped exactly the methods that had forecast too low
        acc = d["origins"][k]["accuracy"]
        assert all((dec["per_origin"][k]["protection"][m]["effect"] == "helped") == (acc.loc[m, "gap_mean_signed_error"] > 0) for m in METHODS)
        assert all(dec["per_origin"][k]["protection"][m]["effect"] != "no material difference" for m in METHODS)
    return ("With equal protection there is still no clear winner: ExtraTrees-24 alone was joint best at Origin 1 and Seasonal naive alone at Origin 2. "
            "Neither previous winner still wins: SARIMA-24 (cheapest unprotected plan at Origin 1) and Persistence (cheapest at Origin 2) both rank 5th of 5 once "
            "every method is protected. "
            f"Seasonal naive ranks first overall ({money(c.loc['Seasonal naive', 'combined_protected_excess'])}m above hindsight over both origins, against "
            f"{money(c.loc['ExtraTrees-24', 'combined_protected_excess'])}m for ExtraTrees-24), and ExtraTrees-24 has the lowest mean pinball loss at 0.9 "
            f"({beds(cal['mean_pinball_090'])} beds) but is not clearly the best calibrated, because SARIMA-24 was lower at Origin 2. "
            "The result is not robust to the shortfall penalty: Mean-24 is the clear winner at 1,000, there is no clear winner at 2,500 or 5,000, and Seasonal naive is "
            "the clear winner at 10,000 (indicative only). "
            f"The margins were wider than these two windows needed (the 0.9 quantile covered the actual gap in {covered} of {months} method-months), so protection "
            "helped every method that had forecast too low and hurt every method that had forecast too high; two windows cannot show which method is best.")


