        f"because SARIMA-24 did not converge, leaving {paths['O1_sep2025']} past six-month error paths at Origin 1 and {paths['O2_mar2026']} at Origin 2. Adding "
        "each error path to the method's forecast gives a set of scenarios; occupied and available errors from the same backtest stay together. The "
