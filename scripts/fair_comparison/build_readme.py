        "happened to run low was punished. Persistence at Origin 2 is the clearest case: it carried a winter level into summer, was above the actual gap in "
        "every month, and had the cheapest plan. That comparison partly measures which forecast leaned high in a given window. Here every method gets the same "
        "deliberate protection, built from its own past errors, so leaning high is no longer a free advantage.", "",
        "### Method", "",
        f"For each method we repeat its forecast at every earlier month that leaves 24 months of training data and six months of known outcomes before the "
